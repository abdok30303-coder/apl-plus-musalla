    /* A Samsung service, plugin or internal screen that still reports show=true. It used to be
       dropped outright: nothing could bring it back if the filter was wrong. It is now kept with
       system:true and hidden from the Home Screen (launcher.js), with Settings › Apps ›
       System Components to show it again. Nothing is deleted or disabled on the screen. */
    var NEVER_FILTER = /^(org\.tizen\.browser|vetrotvapp|com\.samsung\.tv\.store)/i;
    function looksLikeSystem(id, name) {
        if (isDummyYouTube(id, name)) return false;
        if (!SYSTEM_ID.test(id)) return false;
        if (NEVER_FILTER.test(id)) return false;
        if (FAVORITES.indexOf(id) !== -1 || isTizenTube(id, name)) return false;
        if (PRELOADED.indexOf(id) !== -1) return false;
        if (/^org\.tizen\.browser/.test(id)) return false;
        if (STORE_ID.test(id)) return false;
        var n = String(name || "").trim();
        for (var k = 0; k < CAT_BY_NAME.length; k++) {
            var c = CAT_BY_NAME[k].c;
            if (!CAT_BY_NAME[k].re.test(n)) continue;
            if (c.system) return false;                 // Samsung TV Plus and other real apps
        }
        if (CAT_BY_ID[id]) return false;                // apps the catalogue knows
        return true;
    }

    function hasTizen() {
        return typeof global.tizen !== "undefined" &&
               global.tizen.application &&
               typeof global.tizen.application.getAppsInfo === "function";
    }

    /* Images: on the screen, or on GitHub if they come from an update (boot.js) */
    function asset(p) { return p && global.APL_ASSET ? global.APL_ASSET(p) : p; }

    function decorate(app) {
        var m = lookup(app.id, app.name);
        var custom = null;
        try {
            var customMap = JSON.parse(global.localStorage.getItem("apl.customIcons") || "{}") || {};
            custom = customMap[app.id] || null;
        } catch (e) {}
        return {
            id: app.id,
            name: m.name || app.name || app.id,
            icon: app.icon || null,
            accent: m.accent || app.accent || null,
            eyebrow: global.APL.t(m.eyebrow || "APP"),
            tile: custom || asset(m.tile) || null,
            customTile: !!custom,
            key: m.key || null,
            live: m.live || null,             // "youtube" for TizenTube             // full-frame artwork of the tile (like tvOS icons)
            favorite: favorites().indexOf(app.id) !== -1 || isTizenTube(app.id, app.name) || isDummyYouTube(app.id, app.name)
        };
    }

    /* Favourites first (in declared order), then the rest alphabetically. */
    function order(apps) {
        var favRank = {};
        favorites().forEach(function (id, i) { favRank[id] = i; });
        apps.forEach(function (a) {
            if (a.name === "TizenTube") favRank[a.id] = -2;
            else if (isDummyYouTube(a.id, a.name)) favRank[a.id] = -1;
        });
        return apps.slice().sort(function (a, b) {
            var fa = (a.id in favRank), fb = (b.id in favRank);
            if (fa && fb) return favRank[a.id] - favRank[b.id];
            if (fa) return -1;
            if (fb) return 1;
            return a.name.localeCompare(b.name, global.APL.locale, { sensitivity: "base" });
        });
    }

    /* A single App Store tile: the screen sometimes lists two entries for the Samsung
       store (the store and the old Apps panel). com.samsung.tv.store is kept. */
    function dedupe(apps) {
        var stores = apps.filter(function (a) { return STORE_ID.test(a.id); });
        if (stores.length < 2) return apps;
        var keep = stores.filter(function (a) { return a.id === "com.samsung.tv.store"; })[0] || stores[0];
        return apps.filter(function (a) { return !STORE_ID.test(a.id) || a === keep; });
    }

    function loadApps() {
        return new Promise(function (resolve) {
            if (!hasTizen()) {
                resolve(order(DEMO_APPS.map(decorate)));
                return;
            }
            try {
                global.tizen.application.getAppsInfo(function (list) {
                    var apps = [], systems = [];
                    for (var i = 0; i < list.length; i++) {
                        var a = list[i];
                        // `show:true` == meant to appear in the real Samsung menu.
                        // This is what strips the ~250 internal services.
                        if (!a.show && !isDummyYouTube(a.id, a.name)) continue;
                        if (BLOCKLIST[a.id]) continue;
                        if (!isRealApp(a.id, a.name)) {
                            // Kept aside, not dropped: Settings › Apps › System Components shows it again
                            if (looksLikeSystem(a.id, a.name)) {
                                var sy = decorate({ id: a.id, name: a.name, icon: a.iconPath });
                                sy.system = true;
                                systems.push(sy);
                            }
                            continue;
                        }
                        apps.push(decorate({ id: a.id, name: a.name, icon: a.iconPath }));
                    }
                    systemApps = systems;
                    // A screen that answers with nothing gets nothing: the demo apps are for the PC
                    // preview only. Showing them here made the launcher look populated when the
                    // enumeration had in fact failed.
                    if (!apps.length) { resolve([]); return; }
                    // Overscan takes the place of Samsung Internet
                    overscanInstalled = apps.some(function (a) { return a.id === OVERSCAN; });
                    if (overscanInstalled) apps = apps.filter(function (a) { return !/^org\.tizen\.browser/.test(a.id); });
                    resolve(order(dedupe(apps)));
                }, function () {
                    resolve([]);            // enumeration refused: no apps, and no pretend ones
                });
            } catch (e) {
                resolve([]);
            }
        });
    }

    /* Websites added as apps (they open in Internet). The list is
       personal: "webApps" in js/keys.local.js (never published), filled in
       by APL Launcher Setup. E.g.: webApps: [{ name: "My site", url: "https://example.com/" }] */
    function slug(s) { return String(s || "").toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, ""); }

    var overscanInstalled = false;
    var systemApps = [];
    /* Overscan receives no address at launch: it reads the page to start on from its settings
       file. We write it there (without changing the file's owner), then restart it.
       Already open on that site: it resumes as it was, video included. */
    var OVERSCAN_SETTINGS = "/opt/usr/home/owner/apps_rw/" + OVERSCAN + "/data/settings.tsv";
    var overscanUrl = null;
    function openInOverscan(url) {
        if (!/^https?:\/\/[^\s'"\\]+$/.test(url)) return Promise.reject(new Error(global.APL.t("Invalid address")));
        return global.APL.sys.runningApps().then(function (ids) {
            if (overscanUrl === url && ids.indexOf(OVERSCAN) !== -1) return launchApp(OVERSCAN);
            overscanUrl = url;
            var F = OVERSCAN_SETTINGS;
            var cmd = "app_launcher -k " + OVERSCAN + " >/dev/null 2>&1; " +
                "touch '" + F + "'; chown owner:system_share '" + F + "'; chsmack -a 'User::Pkg::" + OVERSCAN + "' '" + F + "'; " +
                "{ grep -vE '^(startup|hints)' '" + F + "'; echo 'hints\t0'; echo 'startupMode\turl'; echo 'startupUrl\t" + url + "'; } > /tmp/apl-overscan.tsv; " +
                "cat /tmp/apl-overscan.tsv > '" + F + "'; rm -f /tmp/apl-overscan.tsv; app_launcher -s " + OVERSCAN + " >/dev/null 2>&1; true";
            return global.APL.sys.exec(cmd).then(function () {});
        });
    }

    function openUrl(url) {
        if (overscanInstalled) return openInOverscan(url);
        return new Promise(function (resolve, reject) {
            if (!hasTizen() || !global.tizen.ApplicationControl || !global.tizen.application.launchAppControl) {
                reject(new Error(global.APL.t("PC preview: would open {url} in Internet", { url: url })));
                return;
            }
            var ctl = new global.tizen.ApplicationControl("http://tizen.org/appcontrol/operation/view", url, null, null, null);
            global.tizen.application.launchAppControl(ctl, "org.tizen.browser", function () { resolve(); }, function () {
                // Fallback: the browser chosen by the screen
                global.tizen.application.launchAppControl(ctl, null, function () { resolve(); },
                    function (e) { reject(new Error((e && e.message) || global.APL.t("Can't open Internet"))); });
            });
        });
    }

    function webApps() {
        var list = (global.APL_KEYS && global.APL_KEYS.webApps) || [];
        return list.filter(function (w) { return w && w.name && /^https?:\/\//.test(w.url || ""); }).map(function (w) {
            var a = decorate({ id: "web." + slug(w.name), name: w.name, icon: null });
            a.virtual = true; a.web = true; a.url = w.url; a.live = w.live || a.live;
            a.run = function () {
                openUrl(w.url).catch(function (e) { if (global.APL.toast) global.APL.toast(e.message); });
            };
            return a;
        });
    }

    function launchApp(id) {
        return new Promise(function (resolve, reject) {
            if (!hasTizen() || typeof global.tizen.application.launch !== "function") {
                reject(new Error(global.APL.t("PC preview: launch unavailable ({id})", { id: id })));
                return;
            }
            function plain() {
                global.tizen.application.launch(id, function () { resolve(); },
                    function (e) { reject(new Error((e && e.message) || global.APL.t("Can't launch the app"))); });
            }
            // Already open: it comes back as it was. Without SkipReload, the screen reloads
            // the whole web app (and TizenTube starts over from scratch through TizenBrew).
            global.APL.sys.runningApps().then(function (ids) {
                if (ids.indexOf(id) === -1) { plain(); return; }
                resumeApp(id, resolve, plain);
            }, plain);
        });
    }
    /* An item from the app's own Smart Hub rows, opened the way Samsung's home opens its tiles: the
       tile's data in PAYLOAD, operation eden_resume. Apps read it at start-up only (a running Plex comes
       to the front but stays where it was), so a running app starts again. As root, through Vetro:
       the payload goes base64, Vetro doubles backslashes. */
    function launchDeepLink(id, data) {
        if (!/^[A-Za-z0-9]{10}[.][A-Za-z0-9._-]+$/.test(id)) return Promise.reject(new Error(global.APL.t("Can't launch the app")));
        var b64 = global.btoa(unescape(encodeURIComponent(JSON.stringify({ values: data }))));
        var bin = "/opt/usr/apps/" + id.split(".")[0] + "/bin/" + id;
        return global.APL.sys.exec("for p in $(ps -eo pid,args | awk '$2 == \"" + bin + "\" {print $1}'); do kill $p; done; sleep 1; " +
            "P=$(printf '%s' '" + b64 + "' | base64 -d); " +
            "app_launcher -s " + id + " __APP_SVC_OP_TYPE__ http://samsung.com/appcontrol/operation/eden_resume PAYLOAD \"$P\" 2>&1 | tail -1").then(function (r) {
            if (!/launched/.test(String(r.output || ""))) throw new Error(global.APL.t("Can't launch the app"));
        });
    }
    function resumeApp(id, ok, failed) {
        try {
            var T = global.tizen;
            var ctl = new T.ApplicationControl("http://tizen.org/appcontrol/operation/default", null, null, null,
                                               [new T.ApplicationControlData("SkipReload", ["Yes"])]);
            T.application.launchAppControl(ctl, id, function () { ok(); }, failed);
        } catch (e) { failed(); }
    }

    /* TizenTube without going through TizenBrew's screen. If it is already running, it comes back as it
       was, video included. Otherwise TizenBrew starts, restarts itself in debug mode (the screen briefly
       goes back through Samsung's home), then waits for the module to be chosen: the screen makes that
       choice itself (the launcher, in the background, can no longer do anything at that point). */
    var BREW = "xvvl3S1bvH.TizenBrewStandalone";
    function tubeWatcher() {
        return "(n=0; seen=0; while [ $n -lt 40 ]; do sleep 1; n=$((n+1)); " +
            "a=$(vconftool get memory/appfw/current_fullscreen_appid 2>/dev/null); " +
            "case \"$a\" in " +
            "*csfs*|*home.sidebar*|*coba.newhome*|*home.media*) seen=1; app_launcher -s " + MY_APP_ID + ";; " +
            "*TizenBrew*) if [ $seen = 1 ] || [ $n -ge 12 ]; then sleep 4; input_keyevent Down; sleep 1; input_keyevent Return; break; fi;; " +
            "esac; done) >/dev/null 2>&1 &";
    }
    function launchTizenTube() {
        return global.APL.sys.runningApps().then(function (ids) {
            if (ids.indexOf(BREW) !== -1) return launchApp(BREW);
            global.APL.holdVeil(24000);
            return global.APL.sys.exec(tubeWatcher()).then(function () { return launchApp(BREW); }, function () { return launchApp(BREW); });
        });
    }

    /* v8.7.42: open a YouTube video the way the user wants: 1) the "YouTube Dummy" app on this TV, 2) TizenTube, 3) the installed YouTube app,
       4) last resort the TV browser. The video id goes both in the link and in PAYLOAD ("v=ID"), the form YouTube apps read at start-up.
       Whether each app then plays the video itself depends on the app: untested on the TV. */
    function openYouTube(videoId) {
        var url = "https://www.youtube.com/watch?v=" + videoId;
        return new Promise(function (resolve, reject) {
            var T = global.tizen;
            function browser() { openUrl(url).then(function () { resolve("browser"); }, reject); }
            if (!hasTizen() || !T.application || typeof T.application.getAppsInfo !== "function" || !T.ApplicationControl) { browser(); return; }
            T.application.getAppsInfo(function (list) {
                var dummy = null, tube = null, yt = null, i, a;
                for (i = 0; i < list.length; i++) {
                    a = list[i];
                    if (isDummyYouTube(a.id, a.name)) dummy = dummy || a.id;
                    else if (a.id === BREW || isTizenTube(a.id, a.name)) tube = tube || a.id;
                    else if (/^(9Ur5IzDKqV\.TizenYouTube|9uQXbeqlCA\.YouTube|111299001912)$/.test(a.id)) yt = yt || a.id;
                }
                /* v8.7.44: the app that reads the video is tried first. The Samsung YouTube app takes the video as PAYLOAD "v=ID" with the
                   plain "default" operation (the form Samsung's own cast and SmartThings launch use); the JSON-wrapped payload of 8.7.42-8.7.43
                   only opened its home screen. TizenTube takes it as the module's args (the way its own DIAL service starts it). The Dummy app
                   is a stand-in whose behaviour is unknown, so it comes after them. A launch that "succeeds" cannot be told from one that
                   only opened the home screen, so the last resort (the browser) is the one that surely opens the video. */
                var order = [];
                if (yt) order.push(["youtube", yt]);
                if (tube) order.push(["tube", tube]);
                if (dummy) order.push(["dummy", dummy]);
                function next(k) {
                    if (k >= order.length) { browser(); return; }
                    var kind = order[k][0], id = order[k][1];
                    try {
                        var ctl;
                        if (kind === "tube") {
                            ctl = new T.ApplicationControl("http://tizen.org/appcontrol/operation/view", null, null, null,
                                [new T.ApplicationControlData("module", [JSON.stringify({ moduleName: "@foxreis/tizentube", moduleType: "npm", args: "v=" + videoId })])]);
                            T.application.launchAppControl(ctl, BREW, function () { resolve(kind); }, function () { next(k + 1); });
                            return;
                        }
                        ctl = new T.ApplicationControl("http://tizen.org/appcontrol/operation/default", null, null, null,
                            [new T.ApplicationControlData("PAYLOAD", ["v=" + videoId])]);
                        T.application.launchAppControl(ctl, id, function () { resolve(kind); }, function () { next(k + 1); });
                    } catch (e) { next(k + 1); }
                }
                next(0);
            }, browser);
        });
    }

    /* v8.7.46: the Ramadan & Eid songs stream from the archive.org links the user supplied (nothing is stored in the launcher or
       the release). A small full-screen player: OK = pause / play, Left / Right = 10 s back / forward, Back or Stop = close. If the file
       cannot start within 15 s, or fails, the YouTube route (openYouTube) is used instead. */
    var SONG_PLAYER = null;
    function closeSongPlayer() {
        var p = SONG_PLAYER; if (!p) return; SONG_PLAYER = null;
        songListeners(false);
        try { if (global.APL && global.APL.settings && global.APL.settings.isOpen && global.APL.settings.isOpen()) global.APL.settings.close(); } catch (e) {}
        try { clearInterval(p.tick); clearTimeout(p.guard); p.audio.pause(); p.audio.removeAttribute("src"); p.audio.load(); } catch (e) {}
        try { if (p.box && p.box.parentNode) p.box.parentNode.removeChild(p.box); } catch (e) {}
    }
    function playSongStream(song) {
        var doc = global.document, A = global.APL;
        closeSongPlayer();
        function fallback() {
            closeSongPlayer();
            if (A.toast) A.toast(A.t(song.yt ? "Couldn't stream the song, opening YouTube" : "Couldn't play the song"), false);
            if (song.yt && A.openYouTube) A.openYouTube(song.yt).catch(function () {});
        }
        try { if (A.quranAudio && A.quranAudio.pause) A.quranAudio.pause(); } catch (e) {}
        try { if (A.radio && A.radio.isPlaying && A.radio.isPlaying()) A.radio.stop(); } catch (e) {}
        var box = doc.createElement("div");
        box.style.cssText = "position:fixed;left:0;top:0;right:0;bottom:0;z-index:99999;background:rgba(6,10,20,.94);color:#fff;display:flex;flex-direction:column;align-items:center;justify-content:center;font-family:inherit;text-align:center";
        var ttl = doc.createElement("div"); ttl.style.cssText = "font-size:54px;font-weight:700;color:#ffe2a0;margin:0 80px 30px"; ttl.textContent = song.title;
        var st = doc.createElement("div"); st.style.cssText = "font-size:34px;opacity:.9;margin-bottom:26px"; st.textContent = A.t("Loading…");
        var bar = doc.createElement("div"); bar.style.cssText = "width:1000px;height:10px;border-radius:5px;background:rgba(255,255,255,.2);overflow:hidden";
        var fill = doc.createElement("div"); fill.style.cssText = "width:0;height:100%;background:#ffd98a"; bar.appendChild(fill);
        var tm = doc.createElement("div"); tm.style.cssText = "font-size:30px;margin-top:18px;direction:ltr"; tm.textContent = "0:00";
        var hint = doc.createElement("div"); hint.style.cssText = "font-size:26px;opacity:.7;margin-top:34px"; hint.textContent = A.t("OK: pause / play   Left / Right: 10 s   Back: close");
        box.appendChild(ttl); box.appendChild(st); box.appendChild(bar); box.appendChild(tm); box.appendChild(hint);
        doc.body.appendChild(box);
        var au = new global.Audio(); au.preload = "auto";
        var p = SONG_PLAYER = { box: box, audio: au, tick: 0, guard: 0 };
        songListeners(true);
        function fmt(s) { s = Math.max(0, Math.floor(s || 0)); return Math.floor(s / 60) + ":" + (s % 60 < 10 ? "0" : "") + (s % 60); }
        au.addEventListener("playing", function () { clearTimeout(p.guard); st.textContent = A.t("Playing"); });
        au.addEventListener("waiting", function () { if (SONG_PLAYER === p) st.textContent = A.t("Loading…"); });
        au.addEventListener("pause", function () { if (SONG_PLAYER === p && !au.ended) st.textContent = A.t("Paused"); });
        au.addEventListener("ended", function () { closeSongPlayer(); });
        au.addEventListener("error", function () { if (SONG_PLAYER === p) fallback(); });
        p.tick = setInterval(function () {
            if (SONG_PLAYER !== p) return;
            var d = au.duration;
            fill.style.width = (d > 0 ? Math.min(100, au.currentTime / d * 100) : 0) + "%";
            tm.textContent = fmt(au.currentTime) + (d > 0 && isFinite(d) ? " / " + fmt(d) : "");
        }, 500);
        p.guard = setTimeout(function () { if (SONG_PLAYER === p && (au.paused || au.readyState < 3)) fallback(); }, 15000);
        au.src = song.url;
        try { var pr = au.play(); if (pr && pr.catch) pr.catch(function () { if (SONG_PLAYER === p && au.error) fallback(); }); } catch (e) { fallback(); }
    }
    /* v8.7.46: the player's keys are caught in the capture phase of the window, before the launcher's own key handling, so Back (10009,
       Esc, Backspace, XF86Back) always closes it and stops the sound, whatever else the launcher thinks is in front. The handler is also on
       the TV's hardware-key event, and the sound stops when the page is hidden. */
    function songKey(code, key) {
        var p = SONG_PLAYER; if (!p) return false;
        var au = p.audio;
        if (code === 10009 || code === 27 || code === 8 || code === 413 || code === 38 || code === 40 || code === 10182 || key === "XF86Back" || key === "GoBack" || key === "BrowserBack") { closeSongPlayer(); return true; }
        if (code === 13 || code === 415 || code === 19 || code === 10252) { if (au.paused) { var q = au.play(); if (q && q.catch) q.catch(function () {}); } else au.pause(); return true; }
        if (code === 37 || code === 412) { try { au.currentTime = Math.max(0, au.currentTime - 10); } catch (e) {} return true; }
        if (code === 39 || code === 417) { try { au.currentTime = au.currentTime + 10; } catch (e) {} return true; }
        return false;
    }
    function songDown(e) {
        if (SONG_PLAYER && songKey(e.keyCode, e.key)) { e.preventDefault(); if (e.stopImmediatePropagation) e.stopImmediatePropagation(); else if (e.stopPropagation) e.stopPropagation(); }
    }
    function songUp(e) {
        if (SONG_PLAYER && (e.keyCode === 10009 || e.keyCode === 27 || e.keyCode === 13 || e.keyCode === 8)) { e.preventDefault(); if (e.stopImmediatePropagation) e.stopImmediatePropagation(); }
    }
    function songHw(e) { if (SONG_PLAYER && e && e.keyName === "back") closeSongPlayer(); }
    function songVis() { if (SONG_PLAYER && global.document.hidden) closeSongPlayer(); }
    /* the key listeners exist only while the player is open: they are added when it opens and removed when it closes */
    function songListeners(on) {
        var m = on ? "addEventListener" : "removeEventListener";
        try {
            global[m]("keydown", songDown, true); global[m]("keyup", songUp, true); global[m]("tizenhwkey", songHw, true);
            global.document[m]("visibilitychange", songVis);
        } catch (e) {}
    }
